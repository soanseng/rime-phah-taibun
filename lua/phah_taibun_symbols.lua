function M.func(input, seg, env)
  -- Only respond to backtick trigger
  if not input:match("^`") then
    return
  end
  -- Strip the leading ` and a trailing ` (misfire tolerance, liur-style)
  local code = input:gsub("^`", ""):gsub("`$", "")

  if code == "" then
    -- Directory first (liur parity), then the original flat list so the
    -- existing tone marks / bopomofo / punctuation stay reachable.
    for _, hint in ipairs(HINTS) do
      yield(Candidate("symbol_hint", seg.start, seg._end, hint, "分類"))
    end
    for _, sym in ipairs(SYMBOLS) do
      yield(Candidate("symbol", seg.start, seg._end, sym[1], sym[2]))
    end
  elseif #code == 1 then
    -- Partial code: show the directory lines covering that decade.
    local pat = "%[" .. code
    for _, hint in ipairs(HINTS) do
      if hint:find(pat, 1, false) then
        yield(Candidate("symbol_hint", seg.start, seg._end, hint, "分類"))
      end
    end
  else
    local cat = CATEGORIES[code]
    if cat then
      local label = string.format("%s %s", code, cat.name)
      for _, sym in ipairs(cat.symbols) do
        yield(Candidate("symbol", seg.start, seg._end, sym, label))
      end
    end
  end
end

return M